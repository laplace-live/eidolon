    await expect(facts.onContext(turnOf(context, {}, controller.signal))).rejects.toThrow("gone");
    expect(context.hiddenCalls).toEqual([]);
    expect(facts.lastQuery).toBeNull();
    await archive.onContext(turnOf(context));
    expect(retriever.calls).toHaveLength(1);
