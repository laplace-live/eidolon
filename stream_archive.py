"""Stream archive — LanceDB-backed RAG over past stream transcripts.

``StreamArchiveService`` is a Pipecat ``FrameProcessor`` that intercepts
``LLMContextFrame``, searches the local LanceDB ``stream_chunks`` table
for transcript chunks relevant to the latest user message, and injects
the top matches as a system message before the LLM runs. Mirrors the
shape of ``pipecat.services.mem0.memory.Mem0MemoryService`` so it slots
into the pipeline the same way.

Sister service: ``persona_facts.PersonaFactsService`` (same pipeline
position, different table). Shared embedding + LanceDB infra lives in
``embeddings.py``.

Storage layout::

    server/
      streams/                          # markdown source of truth (committed)
        2026-04-15-zelda.md
      data/lancedb/                     # built index (committed, regenerated by ingest)
        stream_chunks.lance/            # ← this service reads this table

Run ``uv run python -m tools.ingest_streams`` to (re)build the index.
"""

from __future__ import annotations

import asyncio
import json
import os
from pathlib import Path
from typing import Any, cast

from lancedb.table import Table
from loguru import logger
from pipecat.frames.frames import Frame, LLMContextFrame
from pipecat.processors.frame_processor import FrameDirection, FrameProcessor
from pydantic import BaseModel, Field

from embeddings import DEFAULT_DB_PATH, embed_texts, open_table

DEFAULT_TABLE = "stream_chunks"


class StreamArchiveService(FrameProcessor):
    """RAG over past stream transcripts, fronted as a Pipecat FrameProcessor.

    Mirrors ``Mem0MemoryService``:

    - Intercepts every ``LLMContextFrame`` flowing toward the LLM.
    - Pulls the latest user message, embeds it, queries LanceDB.
    - Injects the top-k matching chunks as a single system message.
    - Forwards the (now-enriched) frame downstream.

    Place this between the user aggregator and the LLM. If you also use
    ``Mem0MemoryService``, both can coexist — they each insert one system
    message per turn.
    """

    class InputParams(BaseModel):
        """Tunables for stream-archive retrieval."""

        top_k: int = Field(default=3, ge=1, le=20)
        """How many chunks to inject per turn. Each chunk is ~5 minutes of
        transcript (~500-1500 tokens), so keep this small."""

        min_query_chars: int = Field(default=4, ge=1)
        """Skip retrieval for short queries like "hi" or "嗯" — they
        embed poorly and would inject noise."""

        system_prompt: str = Field(
            default=(
                "Relevant moments from your past streams (use them to ground "
                "your reply, but do not read them verbatim):\n\n"
            )
        )
        """Prefix prepended to the injected memory block."""

        position: int = Field(default=2, ge=0)
        """Where to insert the memory message inside ``context.get_messages()``.

        Note: ``system_instruction`` is set on the LLM service, not stored in
        the context — so on the first turn ``context.get_messages()`` is just
        ``[user_msg]`` and any ``position >= 1`` clamps to "append at end."
        With Mem0 (default position 1) and StreamArchive (default 2) both
        enabled, the resulting message order before the LLM is roughly:
        ``[user, mem0_memories, archive_chunks]``. The system_instruction
        gets prepended automatically by the LLM service at request time.
        Lower this to 0 if you want stream context placed before the user
        message instead of after.
        """

        embed_model: str | None = Field(default=None)
        """Override the embedding model. Falls back to ``EMBED_MODEL``
        env var, then ``google/gemini-embedding-2-preview``. Must match
        what was used at ingest time, or vectors won't be comparable."""

    def __init__(
        self,
        *,
        db_path: str | os.PathLike[str] = DEFAULT_DB_PATH,
        table_name: str = DEFAULT_TABLE,
        params: InputParams | None = None,
    ):
        """Initialize the stream-archive service.

        Args:
            db_path: Filesystem path to the LanceDB directory.
            table_name: Table within the LanceDB database.
            params: Retrieval tunables. See :class:`InputParams`.
        """
        super().__init__()
        self._params = params or StreamArchiveService.InputParams()
        self._table_name = table_name
        self._db_path = Path(db_path)
        self._table: Table | None = open_table(self._db_path, self._table_name)
        self._last_query: str | None = None

        if self._table is None:
            logger.warning(
                f"StreamArchiveService: no LanceDB table at "
                f"{self._db_path}/{self._table_name}.lance — retrieval will be a no-op. "
                "Run `uv run python -m tools.ingest_streams` after authoring streams/."
            )
        else:
            logger.info(
                f"StreamArchiveService initialized with {self._table.count_rows()} chunks"
            )

    def _reopen_table(self) -> None:
        """Re-open the LanceDB table to pick up files written by a re-ingest.

        ``tools/ingest_streams.py`` drops + recreates the table on every run, which
        invalidates the filenames our cached ``Table`` handle was holding
        (LanceDB stores per-version data files). We detect that at search
        time (``lance error: Not found``) and re-open once.
        """
        try:
            new_table = open_table(self._db_path, self._table_name)
        except Exception as e:
            logger.error(f"StreamArchiveService re-open failed: {e}")
            self._table = None
            return
        if new_table is None:
            logger.warning(
                f"StreamArchiveService re-open: no table at "
                f"{self._db_path}/{self._table_name}.lance"
            )
            self._table = None
            return
        self._table = new_table
        logger.info(
            f"StreamArchiveService re-opened table ({new_table.count_rows()} chunks)"
        )

    async def _search(self, query: str) -> list[dict[str, Any]]:
        """Embed the query and pull the top-k matching chunks.

        Logs at INFO level so retrieval activity is visible without flipping
        loguru to DEBUG. Recovers once from the stale-table error you get
        when ``tools/ingest_streams.py`` runs while the bot is alive.
        """
        if self._table is None:
            logger.warning("Archive search skipped: no table loaded")
            return []

        try:
            vectors = await embed_texts([query], model=self._params.embed_model)
        except Exception as e:
            logger.error(f"Archive embed failed for query={query!r}: {e}")
            return []
        if not vectors:
            return []

        top_k = self._params.top_k
        for attempt in (1, 2):
            table = self._table
            if table is None:
                return []
            try:
                results = await asyncio.to_thread(
                    lambda: table.search(vectors[0]).limit(top_k).to_list()
                )
                if results:
                    best = results[0].get("_distance", float("nan"))
                    dates = sorted({r.get("stream_date", "?") for r in results})
                    refined_n = sum(1 for r in results if r.get("refined"))
                    types = sorted({r.get("chunk_type") or "raw" for r in results})
                    logger.info(
                        f"Archive hit: query={query!r} → {len(results)} chunks "
                        f"(best_dist={best:.3f}, dates={dates}, "
                        f"refined={refined_n}/{len(results)}, types={types})"
                    )
                else:
                    logger.info(f"Archive miss: query={query!r} returned 0 chunks")
                return results
            except Exception as e:
                # LanceDB raises a generic Exception for "Not found" on stale
                # data files. Match on the substring rather than an exception
                # subclass because lance-namespace doesn't expose typed errors.
                if attempt == 1 and "Not found" in str(e):
                    logger.warning(
                        "Archive hit stale table (likely re-ingested while bot was "
                        "running); re-opening and retrying once."
                    )
                    self._reopen_table()
                    continue
                logger.error(f"Archive search failed for query={query!r}: {e}")
                return []
        return []

    @staticmethod
    def _format_chunks(chunks: list[dict[str, Any]], prefix: str) -> str:
        """Render retrieved chunks as a single readable system message.

        Render priority per chunk (best → fallback):

        1. v2 refined: ``details`` narrative + structured SC list +
           ``key_quotes`` block. Rich and grounded in source material.
        2. v1 refined: ``summary`` only.
        3. Unrefined: raw ``text`` (the noisy original transcript).

        For ``sc_events`` specifically we render a per-viewer list with
        the SC content + 奶绿's response — that's what lets the persona
        recall who said what when a viewer asks.
        """
        lines = [prefix]
        for i, chunk in enumerate(chunks, 1):
            date = chunk.get("stream_date", "unknown date")
            heading = chunk.get("heading", "")
            summary = chunk.get("summary") or ""
            details = chunk.get("details") or ""
            text = chunk.get("text", "")

            # Decode the v2 extras blob if present.
            extras_raw = chunk.get("extras_json") or ""
            extras: dict[str, Any] = {}
            if extras_raw:
                try:
                    extras = json.loads(extras_raw)
                except json.JSONDecodeError:
                    extras = {}

            # Per-chunk topics from refine.py (JSON-encoded list[str]).
            # Unrefined chunks store "[]" — decode defensively.
            topics: list[str] = []
            topics_raw = chunk.get("topics") or ""
            if topics_raw:
                try:
                    decoded = json.loads(topics_raw)
                    if isinstance(decoded, list):
                        topics = [str(t) for t in decoded]
                except json.JSONDecodeError:
                    topics = []

            header = f"[{i}] {date}"
            if topics:
                header += f" — {', '.join(topics)}"
            if heading:
                header += f" — {heading}"
            lines.append(header)

            if details:
                # v2: rich narrative + structured SC + quotes
                lines.append(details.strip())
                StreamArchiveService._append_extras(lines, extras)
            elif summary:
                # v1: short summary
                lines.append(summary.strip())
            else:
                # Unrefined fallback: the raw transcript
                lines.append(text.strip())
            lines.append("")
        return "\n".join(lines).rstrip() + "\n"

    @staticmethod
    def _append_extras(lines: list[str], extras: dict[str, Any]) -> None:
        """Append the structured v2 fields (SC events, songs, events,
        quotes) to the rendered chunk in a scannable layout."""
        sc_events = extras.get("sc_events") or []
        if sc_events:
            lines.append("SC回顾:")
            for sc in sc_events:
                viewer = sc.get("viewer") or "?"
                amount = sc.get("amount_yuan")
                content = (sc.get("content") or "").strip()
                response = (sc.get("response") or "").strip()
                head = f"  • {viewer}"
                if amount:
                    head += f"（¥{amount}）"
                if content:
                    head += f": {content}"
                lines.append(head)
                if response:
                    lines.append(f"    → 我的回复: {response}")

        songs = extras.get("songs") or []
        if songs:
            song_titles = []
            for s in songs:
                if isinstance(s, dict):
                    title = (s.get("title") or "").strip()
                    note = (s.get("note") or "").strip()
                    song_titles.append(f"《{title}》{f'（{note}）' if note else ''}")
                elif isinstance(s, str):
                    song_titles.append(f"《{s}》")
            if song_titles:
                lines.append("歌曲: " + "; ".join(song_titles))

        events = extras.get("events") or []
        if events:
            lines.append("事件: " + "; ".join(str(e) for e in events))

        promises = extras.get("promises") or []
        if promises:
            lines.append("承诺: " + "; ".join(str(p) for p in promises))

        quotes = extras.get("key_quotes") or []
        if quotes:
            lines.append("金句:")
            for q in quotes:
                lines.append(f"  · 「{q}」")

    async def _enhance(self, context, query: str) -> None:
        """Inject retrieved chunks into the LLM context as a system message."""
        if self._last_query == query:
            # Same turn; same context being re-emitted (idempotent guard).
            return
        self._last_query = query

        chunks = await self._search(query)
        if not chunks:
            # _search already logged the miss/skip; nothing to inject.
            return

        memory_msg = {
            "role": "system",
            "content": self._format_chunks(chunks, self._params.system_prompt),
        }
        messages = context.get_messages()
        position = max(0, min(self._params.position, len(messages)))
        messages.insert(position, memory_msg)
        context.set_messages(messages)
        logger.info(
            f"Archive injected {len(chunks)} chunks at position {position} "
            f"({len(memory_msg['content'])} chars)"
        )

    async def process_frame(self, frame: Frame, direction: FrameDirection):
        """Intercept ``LLMContextFrame`` and enrich it with stream memories."""
        await super().process_frame(frame, direction)

        if isinstance(frame, LLMContextFrame):
            try:
                context = frame.context
                latest_user_msg = _latest_user_text(context.get_messages())

                if (
                    latest_user_msg
                    and len(latest_user_msg.strip()) >= self._params.min_query_chars
                ):
                    await self._enhance(context, latest_user_msg)

                await self.push_frame(frame)
            except Exception as e:
                await self.push_error(
                    error_msg=f"StreamArchiveService error: {e}", exception=e
                )
                await self.push_frame(frame)
        else:
            await self.push_frame(frame, direction)


def _latest_user_text(messages: list[Any]) -> str | None:
    """Find the most recent user message with string content.

    Pipecat's LLMContext returns typed-dict-like messages whose concrete shape
    varies by provider. At runtime they're plain dicts; this helper does the
    duck-typed access in one place so the rest of the module stays clean.
    """
    for message in reversed(messages):
        msg = cast(dict[str, Any], message)
        if msg.get("role") == "user":
            content = msg.get("content")
            if isinstance(content, str):
                return content
    return None
