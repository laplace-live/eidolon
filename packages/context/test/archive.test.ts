function broadcastsOf(rows: [string, string, number][]): Broadcast[] {
  return rows.map(([day, bv, parts]) => broadcast(day, bv, parts));
}

function scopeJson(scope: StreamScope | null): Record<string, unknown> | null {
  if (scope === null) return null;
  const { startDate, endDate, latest, streamIds, label } = scope;
  return { startDate, endDate, latest, streamIds: [...streamIds], label };
}

function fact(n: number): SearchRow[] {
  return n < 10 ? [{ text: `F${n}`, date: `2026-09-0${n}` }] : [{ text: `F${n}` }];
}

/** A catalog whose reads can be held open, to interrupt the archive mid-await. */
class GatedCatalog extends MemoryCatalog {
  hold: Promise<void> | null = null;
  holdRecent: Promise<void> | null = null;

  override async broadcasts(): Promise<Broadcast[]> {
    if (this.hold) await this.hold;
    return super.broadcasts();
  }

  override async recent(n = 3): Promise<Broadcast[]> {
    if (this.holdRecent) await this.holdRecent;
    return this.items.slice(0, n);
  }
}

describe("archive → facts replays Python's pipeline", () => {
  for (const scenario of scenarios) {
    test(scenario.name, async () => {
      const archiveRetriever = new FakeRetriever(scenario.archiveHits);
      const factsRetriever = new FakeRetriever();
      factsRetriever.search = async (query, options) => {
        const { signal: _signal, ...rest } = options;
        factsRetriever.calls.push({ query, ...rest });
        return fact(factsRetriever.calls.length);
      };
      const catalog = new MemoryCatalog(broadcastsOf(scenario.broadcasts));
      const archive = new StreamArchive({
        retriever: archiveRetriever,
        catalog,
        timeZone: "UTC",
        today: () => TODAY,
      });
      if (scenario.tools) await archive.recallTool();
      const facts = new PersonaFacts({ retriever: factsRetriever });
      const context = new FakeContext();
      const errors: string[] = [];
      const snapshots: Snapshot[] = [];
      for (const step of scenario.steps) {
        if ("add" in step) {
          context.add(structuredClone(step.add));
        } else if ("catalog" in step) {
          catalog.items.splice(
            0,
            catalog.items.length,
            ...new MemoryCatalog(broadcastsOf(step.catalog)).items,
          );
        } else {
          const metadata: Record<string, unknown> = {};
          if (step.frame.decision !== null) {
            metadata[GATE_FRAME_KEY] = GateDecision.settled({
              retrieve: step.frame.decision,
              timeline: false,
            });
          }
          for (const provider of [archive, facts]) {
            try {
              await provider.onContext(turnOf(context, metadata));
            } catch (error) {
              errors.push(provider.errorMessage(error));
            }
          }
          const { [GATE_FRAME_KEY]: _decision, ...rest } = metadata;
          snapshots.push({
            messages: structuredClone(context.messages),
            metadata: rest,
            archiveCalls: structuredClone(archiveRetriever.calls),
            factsCalls: structuredClone(factsRetriever.calls),
            selectedScope: scopeJson(archive.recall.selectedScope),
            lastWasArchive: archive.lastWasArchive,
            errors: [...errors],
          });
        }
      }
      expect(snapshots).toEqual(scenario.snapshots);
    });
  }
});

