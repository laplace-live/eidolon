interface ToolStep {
  nextTurn?: true;
  args?: Record<string, unknown>;
  reply?: Record<string, unknown>;
  calls?: Record<string, unknown>[];
  /** null: Python's context had no tools left to advertise. */
  advertised?: string[] | null;
  selectedScope?: Record<string, unknown> | null;
}

